#!/usr/bin/env python3
"""Generate skills/archguard/reference/rules.md from the spec catalog.

Usage: python3 scripts/gen_skill_reference.py [--check]

--check exits non-zero when the committed file is stale (used by scripts/spec_check.py).
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / 'spec'
TARGET = ROOT / 'skills' / 'archguard' / 'reference' / 'rules.md'
ROLES = [
    'DOMAIN', 'APPLICATION', 'INBOUND_PORT', 'OUTBOUND_PORT',
    'INBOUND_ADAPTER', 'OUTBOUND_ADAPTER', 'COMPOSITION_ROOT',
]
FENCE = {'java': 'java', 'python': 'python', 'typescript': 'ts'}


def load(path):
    with open(path, encoding='utf-8') as handle:
        return yaml.safe_load(handle)


def profile_closure(profiles, pid, seen=None):
    seen = seen if seen is not None else []
    if pid in seen:
        return seen
    seen.append(pid)
    for parent in profiles[pid].get('includes', []):
        profile_closure(profiles, parent, seen)
    return seen


def matrix(profiles, pid):
    """Rows: depending role; cells: the rule that forbids the dependency, or blank if allowed."""
    forbidden = {}
    infra = {}
    for p in profile_closure(profiles, pid):
        for rr in profiles[p].get('roleRules', []):
            for origin in rr['from']:
                for target in rr.get('forbiddenRoles', []):
                    if rr.get('crossRoleOnly') and origin == target:
                        continue
                    forbidden.setdefault((origin, target), rr['rule'])
                if rr.get('forbidInfrastructure'):
                    infra.setdefault(origin, rr['rule'])
    if not forbidden and not infra:
        return None
    short = {r: r.replace('INBOUND_', 'IN_').replace('OUTBOUND_', 'OUT_').replace('COMPOSITION_ROOT', 'ROOT') for r in ROLES}
    lines = ['| from \\ to | ' + ' | '.join(short[r] for r in ROLES) + ' | infrastructure |',
             '|---' * (len(ROLES) + 2) + '|']
    for origin in ROLES:
        cells = [forbidden.get((origin, t), 'ok') for t in ROLES]
        cells.append(infra.get(origin, 'ok'))
        lines.append(f'| **{short[origin]}** | ' + ' | '.join(cells) + ' |')
    return '\n'.join(lines)


def generate():
    index = load(SPEC / 'index.yml')
    profiles = {p: load(SPEC / 'profiles' / f'{p}.yml') for p in index['profiles']}
    rules = [load(SPEC / 'rules' / f'{r}.yml') for r in index['rules']]
    activated_by = {}
    for pid in index['profiles']:
        for p in profile_closure(profiles, pid):
            for rule in profiles[p].get('activates', []):
                activated_by.setdefault(rule, set()).add(pid)

    out = [
        '<!-- Generated by scripts/gen_skill_reference.py from spec/. Do not edit. -->',
        f'# ArchGuard rules reference (spec {index["specVersion"]})',
        '',
        'Roles: `DOMAIN`, `APPLICATION`, `INBOUND_PORT`, `OUTBOUND_PORT`, `INBOUND_ADAPTER`, '
        '`OUTBOUND_ADAPTER`, `COMPOSITION_ROOT`. Types matching no role are `UNCLASSIFIED`.',
        '',
        '## Allowed dependencies by profile',
        '',
        'A cell names the rule that forbids a dependency from the row role to the column role; '
        '`ok` means allowed. `infrastructure` means framework and persistence APIs listed in '
        '`spec/infrastructure/<language>.yml` (for example `jakarta.persistence.`, `org.springframework.`, '
        '`sqlalchemy`, `@nestjs/`). Abbreviations: IN_ = INBOUND_, OUT_ = OUTBOUND_, ROOT = COMPOSITION_ROOT.',
        '',
    ]
    for pid in index['profiles']:
        p = profiles[pid]
        out += [f'### `{pid}`: {p["title"]}', '', ' '.join(p['description'].split()), '']
        if p.get('includes'):
            out += [f'Includes: {", ".join(f"`{i}`" for i in p["includes"])}.', '']
        table = matrix(profiles, pid)
        if table:
            out += [table, '']
        extra = sorted(r for r in p.get('activates', []) if not r.startswith(('HEX-', 'LAYER-')))
        if extra:
            out += [f'Also activates: {", ".join(extra)}.', '']

    out += ['## Rules', '']
    for r in rules:
        when = {
            'always': 'always active',
            'requireClassification': 'active when `requireClassification: true`',
            'optIn': 'off unless enabled under `rules`',
            'profile': 'active with profile ' + ', '.join(f'`{p}`' for p in sorted(activated_by.get(r['id'], []))),
        }.get(r['activation'], r['activation'])
        if r['activation'] != 'profile' and r['id'] in activated_by:
            when += '; also activated by ' + ', '.join(f'`{p}`' for p in sorted(activated_by[r['id']]))
        out += [
            f'### {r["id"]}: {r["title"]}',
            '',
            f'Default severity {r["defaultSeverity"]}; {when}.',
            '',
            f'Why: {" ".join(r["rationale"].split())}',
            '',
            f'Fix: {" ".join(r["remediation"].split())}',
            '',
        ]
        for lang in ('java', 'python', 'typescript'):
            ex = r.get('examples', {}).get(lang)
            if not ex:
                continue
            out += [f'{lang.capitalize()}, violating:', '', f'```{FENCE[lang]}', ex['bad'].rstrip(), '```', '',
                    f'{lang.capitalize()}, compliant:', '', f'```{FENCE[lang]}', ex['good'].rstrip(), '```', '']
    return '\n'.join(out).rstrip() + '\n'


def main():
    text = generate()
    if '--check' in sys.argv:
        if not TARGET.is_file() or TARGET.read_text(encoding='utf-8') != text:
            print(f'{TARGET.relative_to(ROOT)} is stale; run python3 scripts/gen_skill_reference.py')
            sys.exit(1)
        return
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding='utf-8')
    print(f'wrote {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
